#!/usr/bin/env node

/**
 * TestFly MCP Bridge Server
 * Zero-dependency JSON-RPC 2.0 stdio server for TestFly.
 * Provides TestFly Java codegen, action-cache management, and self-healing patch tools.
 */

const fs = require('fs');
const path = require('path');
const readline = require('readline');
const { execSync } = require('child_process');

const SERVER_NAME = 'testfly-bridge';
const SERVER_VERSION = '1.1.0';

const TOOLS = [
  {
    name: 'generate_testfly_code',
    description: 'Generate production-ready TestFly Java 21 test code (BaseTest, BasePage, getByRole, assertThat) from recorded Playwright interactions or DOM inspection.',
    inputSchema: {
      type: 'object',
      properties: {
        className: { type: 'string', default: 'RecordedFlowTest', description: 'Name of the generated Java class' },
        packageName: { type: 'string', default: 'io.testfly.examples.testng', description: 'Java package name' },
        framework: { type: 'string', enum: ['testng', 'junit5', 'page_object'], default: 'testng', description: 'Target framework' },
        actions: {
          type: 'array',
          description: 'List of recorded actions (navigate, click, type, select, assert_title, assert_url, assert_visible, assert_text)',
          items: {
            type: 'object',
            properties: {
              type: { type: 'string' },
              selector: { type: 'string' },
              role: { type: 'string' },
              roleName: { type: 'string' },
              text: { type: 'string' },
              value: { type: 'string' },
              expected: { type: 'string' }
            },
            required: ['type']
          }
        }
      },
      required: ['actions']
    }
  },
  {
    name: 'inspect_action_cache',
    description: 'Read and inspect autonomous act("Goal") action plans frozen in .testfly/action-cache.json for 0ms replay.',
    inputSchema: {
      type: 'object',
      properties: {
        workspaceRoot: { type: 'string', description: 'Root directory of the TestFly project' }
      }
    }
  },
  {
    name: 'manage_action_cache',
    description: 'Invalidate or clear cached action plans in .testfly/action-cache.json so the AI re-compiles them upon next test execution.',
    inputSchema: {
      type: 'object',
      properties: {
        workspaceRoot: { type: 'string', description: 'Root directory of the TestFly project' },
        action: { type: 'string', enum: ['invalidate', 'clear_all'], default: 'invalidate' },
        goal: { type: 'string', description: 'Specific goal name to invalidate' }
      },
      required: ['action']
    }
  },
  {
    name: 'list_remediations',
    description: 'List pending AI self-healing git diff .patch files generated by AiHealingEngine in target/remediations/.',
    inputSchema: {
      type: 'object',
      properties: {
        workspaceRoot: { type: 'string', description: 'Root directory of the TestFly project' }
      }
    }
  },
  {
    name: 'apply_remediation_patch',
    description: 'Apply a self-healing git diff patch from target/remediations/ directly to the Java test source code.',
    inputSchema: {
      type: 'object',
      properties: {
        workspaceRoot: { type: 'string', description: 'Root directory of the TestFly project' },
        patchFilePath: { type: 'string', description: 'Full path to the .patch file' }
      },
      required: ['patchFilePath']
    }
  },
  {
    name: 'init_testfly_project',
    description: 'Scaffold a modern TestFly 1.0.6 Java 21 test automation project with pom.xml, testfly.yml, and sample test.',
    inputSchema: {
      type: 'object',
      properties: {
        directory: { type: 'string', description: 'Target directory for project scaffolding' }
      },
      required: ['directory']
    }
  }
];

function generateLocator(action) {
  if (action.role && action.roleName) {
    return `getByRole(Role.${action.role.toUpperCase()}, new RoleOptions().setName("${action.roleName}"))`;
  }
  if (action.role) {
    return `getByRole(Role.${action.role.toUpperCase()})`;
  }
  if (action.text) {
    return `getByText("${action.text}")`;
  }
  if (action.selector) {
    if (action.selector.startsWith('//') || action.selector.startsWith('(//')) {
      return `find(By.xpath("${action.selector}"))`;
    }
    if (action.selector.startsWith('#')) {
      return `find(By.id("${action.selector.slice(1)}"))`;
    }
    return `find(By.cssSelector("${action.selector}"))`;
  }
  return `find(By.cssSelector("*"))`;
}

function generateStep(action) {
  switch (action.type) {
    case 'navigate':
      return action.value ? `open("${action.value}");` : `open();`;
    case 'click':
      return `${generateLocator(action)}.click();`;
    case 'type':
      return `${generateLocator(action)}.type("${action.value || ''}");`;
    case 'select':
      return `${generateLocator(action)}.selectOption("${action.value || ''}");`;
    case 'assert_title':
      return `assertThatPage().hasTitle("${action.expected || ''}");`;
    case 'assert_url':
      return `assertThatPage().hasUrl("${action.expected || ''}");`;
    case 'assert_visible':
      return `assertThat(${generateLocator(action)}).isVisible();`;
    case 'assert_text':
      return `assertThat(${generateLocator(action)}).hasText("${action.expected || ''}");`;
    default:
      return `// Unsupported action: ${JSON.stringify(action)}`;
  }
}

function handleToolCall(name, args) {
  const root = args.workspaceRoot || process.cwd();

  if (name === 'generate_testfly_code') {
    const className = args.className || 'RecordedFlowTest';
    const pkg = args.packageName || 'io.testfly.examples.testng';
    const steps = (args.actions || []).map(a => `        ${generateStep(a)}`).join('\n');

    const code = `package ${pkg};

import io.testfly.locator.Role;
import io.testfly.locator.RoleOptions;
import io.testfly.test.BaseTest;
import org.openqa.selenium.By;
import org.testng.annotations.Test;

/**
 * Auto-generated by TestFly Bridge from Playwright recording.
 */
public class ${className} extends BaseTest {

    @Test
    public void executeRecordedFlow() {
${steps}
    }
}
`;
    return { content: [{ type: 'text', text: code }] };
  }

  if (name === 'inspect_action_cache') {
    const cachePath = path.join(root, '.testfly', 'action-cache.json');
    if (!fs.existsSync(cachePath)) {
      return { content: [{ type: 'text', text: JSON.stringify({ count: 0, plans: [] }) }] };
    }
    const content = fs.readFileSync(cachePath, 'utf8');
    return { content: [{ type: 'text', text: content }] };
  }

  if (name === 'manage_action_cache') {
    const cachePath = path.join(root, '.testfly', 'action-cache.json');
    if (!fs.existsSync(cachePath)) {
      return { content: [{ type: 'text', text: 'Action cache file does not exist.' }] };
    }
    if (args.action === 'clear_all') {
      fs.writeFileSync(cachePath, '[]', 'utf8');
      return { content: [{ type: 'text', text: 'Cleared all action plans.' }] };
    }
    try {
      const data = JSON.parse(fs.readFileSync(cachePath, 'utf8'));
      const filtered = Array.isArray(data) ? data.filter(p => p.goal !== args.goal) : [];
      fs.writeFileSync(cachePath, JSON.stringify(filtered, null, 2), 'utf8');
      return { content: [{ type: 'text', text: `Invalidated goal: ${args.goal}` }] };
    } catch (e) {
      return { content: [{ type: 'text', text: `Failed: ${e.message}` }] };
    }
  }

  if (name === 'list_remediations') {
    const dir = path.join(root, 'target', 'remediations');
    if (!fs.existsSync(dir)) {
      return { content: [{ type: 'text', text: JSON.stringify({ count: 0, patches: [] }) }] };
    }
    const files = fs.readdirSync(dir).filter(f => f.endsWith('.patch'));
    const patches = files.map(f => ({
      fileName: f,
      filePath: path.join(dir, f),
      content: fs.readFileSync(path.join(dir, f), 'utf8')
    }));
    return { content: [{ type: 'text', text: JSON.stringify({ count: patches.length, patches }, null, 2) }] };
  }

  if (name === 'apply_remediation_patch') {
    try {
      execSync(`git apply "${args.patchFilePath}"`, { cwd: root, stdio: 'pipe' });
      return { content: [{ type: 'text', text: `Successfully applied patch ${path.basename(args.patchFilePath)}` }] };
    } catch (err) {
      return { content: [{ type: 'text', text: `Failed to apply patch: ${err.message}` }] };
    }
  }

  if (name === 'init_testfly_project') {
    const dir = args.directory || path.join(root, 'testfly-suite');
    fs.mkdirSync(dir, { recursive: true });
    fs.mkdirSync(path.join(dir, 'src', 'test', 'java', 'com', 'example', 'tests'), { recursive: true });

    fs.writeFileSync(path.join(dir, 'testfly.yml'), `# TestFly Configuration
execution:
  mode: local
  baseUrl: https://example.com
  parallel: methods
  threadCount: 4

browser:
  name: chrome
  headless: false
  lifecycle: per-test

retry:
  enabled: true
  maxAttempts: 2

timeouts:
  explicit: 10
  pageLoad: 30

reporting:
  html:
    enabled: true
    title: TestFly Test Automation Report
`, 'utf8');

    fs.writeFileSync(path.join(dir, 'pom.xml'), `<?xml version="1.0" encoding="UTF-8"?>
<project xmlns="http://maven.apache.org/POM/4.0.0"
         xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
         xsi:schemaLocation="http://maven.apache.org/POM/4.0.0 http://maven.apache.org/xsd/maven-4.0.0.xsd">
    <modelVersion>4.0.0</modelVersion>

    <groupId>com.example</groupId>
    <artifactId>testfly-suite</artifactId>
    <version>1.0.0-SNAPSHOT</version>

    <properties>
        <maven.compiler.release>21</maven.compiler.release>
        <project.build.sourceEncoding>UTF-8</project.build.sourceEncoding>
        <testfly.version>1.0.7</testfly.version>
    </properties>

    <dependencies>
        <dependency>
            <groupId>io.github.hakanngul</groupId>
            <artifactId>testfly</artifactId>
            <version>\${testfly.version}</version>
            <scope>test</scope>
        </dependency>
    </dependencies>

    <build>
        <plugins>
            <plugin>
                <groupId>org.apache.maven.plugins</groupId>
                <artifactId>maven-compiler-plugin</artifactId>
                <version>3.13.0</version>
            </plugin>
            <plugin>
                <groupId>org.apache.maven.plugins</groupId>
                <artifactId>maven-surefire-plugin</artifactId>
                <version>3.2.5</version>
            </plugin>
        </plugins>
    </build>
</project>
`, 'utf8');

    fs.writeFileSync(path.join(dir, 'src', 'test', 'java', 'com', 'example', 'tests', 'SampleWebTest.java'), `package com.example.tests;

import io.testfly.test.BaseTest;
import org.testng.annotations.Test;

public class SampleWebTest extends BaseTest {

    @Test
    public void testExampleDotCom() {
        open("/");
        assertThatPage().hasTitle("Example Domain");
    }
}
`, 'utf8');

    return { content: [{ type: 'text', text: `Scaffolded TestFly project at ${dir}` }] };
  }

  throw new Error(`Unknown tool: ${name}`);
}

// CLI argument handling
const cliArgs = process.argv.slice(2);
if (cliArgs.length > 0) {
  const command = cliArgs[0];
  if (command === 'init') {
    const targetDir = cliArgs[1] || 'testfly-suite';
    const targetPath = path.resolve(process.cwd(), targetDir);
    const result = handleToolCall('init_testfly_project', { directory: targetPath });
    console.log(`✈️  ${result.content[0].text}`);
    console.log(`Next steps:\n  cd ${targetDir}\n  mvn test`);
    process.exit(0);
  }
  if (command === '--version' || command === '-v') {
    console.log(`${SERVER_NAME} v${SERVER_VERSION}`);
    process.exit(0);
  }
  if (command === '--help' || command === '-h') {
    console.log(`Usage:
  npx @testfly/mcp init [directory]   Scaffold a ready-to-run TestFly Java 21 test suite
  npx @testfly/mcp                    Start stdio JSON-RPC MCP server for Cursor / Claude`);
    process.exit(0);
  }
}

// JSON-RPC stdio loop
const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  terminal: false
});

rl.on('line', (line) => {
  if (!line.trim()) return;
  try {
    const msg = JSON.parse(line);
    const { id, method, params } = msg;

    if (method === 'initialize') {
      const response = {
        jsonrpc: '2.0',
        id,
        result: {
          protocolVersion: '2024-11-05',
          serverInfo: {
            name: SERVER_NAME,
            version: SERVER_VERSION
          },
          capabilities: {
            tools: {}
          }
        }
      };
      process.stdout.write(JSON.stringify(response) + '\n');
    } else if (method === 'notifications/initialized') {
      // no response required
    } else if (method === 'tools/list') {
      const response = {
        jsonrpc: '2.0',
        id,
        result: {
          tools: TOOLS
        }
      };
      process.stdout.write(JSON.stringify(response) + '\n');
    } else if (method === 'tools/call') {
      try {
        const result = handleToolCall(params.name, params.arguments || {});
        process.stdout.write(JSON.stringify({ jsonrpc: '2.0', id, result }) + '\n');
      } catch (err) {
        process.stdout.write(JSON.stringify({
          jsonrpc: '2.0',
          id,
          error: { code: -32603, message: err.message }
        }) + '\n');
      }
    } else {
      process.stdout.write(JSON.stringify({
        jsonrpc: '2.0',
        id,
        error: { code: -32601, message: 'Method not found' }
      }) + '\n');
    }
  } catch (e) {
    // Ignore invalid JSON lines
  }
});
