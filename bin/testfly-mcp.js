// Constants of io.testfly.locator.Role.
const ROLES = new Set(['BUTTON', 'LINK', 'CHECKBOX', 'RADIO', 'SWITCH', 'TEXTBOX', 'SEARCHBOX', 'COMBOBOX', 'OPTION', 'HEADING', 'IMG', 'LIST', 'LISTITEM', 'TABLE', 'ROW', 'CELL', 'COLUMNHEADER', 'NAVIGATION', 'BANNER', 'CONTENTINFO', 'MAIN', 'REGION', 'ARTICLE', 'DIALOG', 'ALERT', 'ALERTDIALOG', 'TAB', 'TABLIST', 'TABPANEL', 'MENU', 'MENUITEM', 'PROGRESSBAR', 'SPINBUTTON', 'SLIDER', 'PARAGRAPH', 'SEPARATOR']);

/** Java string literal with backslashes, quotes and control characters escaped. */
function javaString(value) {
  return JSON.stringify(String(value ?? '')).replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
}

function generateLocator(action) {
  const role = action.role ? action.role.toUpperCase() : undefined;
  if (role && ROLES.has(role)) {
    return action.roleName
      ? `getByRole(Role.${role}, ${javaString(action.roleName)})`
      : `getByRole(Role.${role})`;
  }
  if (action.text) {
    return `getByText(${javaString(action.text)})`;
  }
  if (action.selector) {
    if (action.selector.startsWith('//') || action.selector.startsWith('(//')) {
      return `find(By.xpath(${javaString(action.selector)}))`;
    }
    if (/^#[A-Za-z][\w-]*$/.test(action.selector)) {
      return `find(By.id(${javaString(action.selector.slice(1))}))`;
    }
    return `find(By.cssSelector(${javaString(action.selector)}))`;
  }
  return `find(By.cssSelector("*"))`;
}

function generateStep(action) {
  switch (action.type) {
    case 'navigate':
      return action.value ? `open(${javaString(action.value)});` : `open();`;
    case 'click':
      return `${generateLocator(action)}.click();`;
    case 'type':
      return `${generateLocator(action)}.type(${javaString(action.value)});`;
    case 'select':
      // TestFly's Locator has no select API; use Selenium's Select on the resolved element.
      return `new Select(${generateLocator(action)}.element()).selectByVisibleText(${javaString(action.value)});`;
    case 'assert_title':
      return `assertThatPage().hasTitle(${javaString(action.expected)});`;
    case 'assert_url':
      return `assertThatPage().hasUrl(${javaString(action.expected)});`;
    case 'assert_visible':
      return `assertThat(${generateLocator(action)}).isVisible();`;
    case 'assert_text':
      return `assertThat(${generateLocator(action)}).hasText(${javaString(action.expected)});`;
    default:
      return `// Unsupported action: ${JSON.stringify(action).replace(/[\r\n]/g, ' ')}`;
  }
}

/** Same key as io.testfly.agent.ActionCache.buildKey: URL path + "::" + lower-cased goal. */
function cacheKey(url, goal) {
  let urlPath = '';
  if (url && String(url).trim()) {
    const absolute = /^[a-z][a-z0-9+.-]*:\/\/[^/?#]*([^?#]*)/i.exec(url);
    const part = absolute ? absolute[1] : String(url).split(/[?#]/)[0];
    urlPath = part.trim() ? part : url;
  }
  return `${urlPath}::${String(goal || '').trim().toLowerCase()}`;
}

function handleToolCall(name, args) {
  const root = args.workspaceRoot || process.cwd();

  if (name === 'generate_testfly_code') {
    const className = args.className || 'RecordedFlowTest';
    const pkg = args.packageName || 'io.testfly.examples.testng';
    const steps = (args.actions || []).map(a => `        ${generateStep(a)}`).join('\n');

    const code = `package ${pkg};

import io.testfly.locator.Role;
import io.testfly.test.BaseTest;
import org.openqa.selenium.By;
import org.openqa.selenium.support.ui.Select;
import org.testng.annotations.Test;

/**
 * Auto-generated by TestFly Bridge from Playwright recording.
 */
public class ${className} extends BaseTest {

    @Test
    public void executeRecordedFlow() {
${steps}
    }
}
`;
    return { content: [{ type: 'text', text: code }] };
  }

  if (name === 'inspect_action_cache') {
    const cachePath = path.join(root, '.testfly', 'action-cache.json');
    if (!fs.existsSync(cachePath)) {
      return { content: [{ type: 'text', text: JSON.stringify({ count: 0, plans: [] }) }] };
    }
    const content = fs.readFileSync(cachePath, 'utf8');
    return { content: [{ type: 'text', text: content }] };
  }

  if (name === 'manage_action_cache') {
    const cachePath = path.join(root, '.testfly', 'action-cache.json');
    if (!fs.existsSync(cachePath)) {
      return { content: [{ type: 'text', text: 'Action cache file does not exist.' }] };
    }
    if (args.action === 'clear_all') {
      // TestFly loads the cache as a JSON object, so an empty cache is {} rather than [].
      fs.writeFileSync(cachePath, '{}\n', 'utf8');
      return { content: [{ type: 'text', text: 'Cleared all action plans.' }] };
    }
    try {
      const data = JSON.parse(fs.readFileSync(cachePath, 'utf8'));
      // Older bridge versions wrote an array; convert it to TestFly's "/path::goal" map.
      const entries = Array.isArray(data)
        ? data.filter(p => p && typeof p.goal === 'string').map(p => [cacheKey(p.urlPattern, p.goal), p])
        : Object.entries(data && typeof data === 'object' ? data : {});
      const goal = String(args.goal || '').trim().toLowerCase();
      const kept = entries.filter(([key, plan]) => args.key
        ? key !== args.key
        : String(plan && plan.goal || '').trim().toLowerCase() !== goal);
      if (kept.length === entries.length) {
        return { content: [{ type: 'text', text: `No cached plan matched ${args.key ? `key "${args.key}"` : `goal "${args.goal}"`}.` }] };
      }
      fs.writeFileSync(cachePath, JSON.stringify(Object.fromEntries(kept), null, 2) + '\n', 'utf8');
      return { content: [{ type: 'text', text: `Invalidated ${entries.length - kept.length} plan(s) for ${args.key || args.goal}.` }] };
    } catch (e) {
      return { content: [{ type: 'text', text: `Failed: ${e.message}` }] };
    }
  }

  if (name === 'list_remediations') {
    const dir = path.join(root, 'target', 'remediations');
    if (!fs.existsSync(dir)) {
      return { content: [{ type: 'text', text: JSON.stringify({ count: 0, patches: [] }) }] };
    }
    const files = fs.readdirSync(dir).filter(f => f.endsWith('.patch'));
    const patches = files.map(f => ({
      fileName: f,
      filePath: path.join(dir, f),
      content: fs.readFileSync(path.join(dir, f), 'utf8')
    }));
    return { content: [{ type: 'text', text: JSON.stringify({ count: patches.length, patches }, null, 2) }] };
  }

  if (name === 'apply_remediation_patch') {
    try {
      if (args.confirm !== true) throw new Error('Review the patch and pass confirm: true before applying it.');
      const dir = fs.realpathSync(path.join(root, 'target', 'remediations'));
      const patch = fs.realpathSync(args.patchFilePath);
      if (path.dirname(patch) !== dir || !patch.endsWith('.patch')) {
        throw new Error('Patch must be a .patch file inside target/remediations.');
      }
      execFileSync('git', ['apply', '--check', patch], { cwd: root, stdio: 'pipe' });
      execFileSync('git', ['apply', patch], { cwd: root, stdio: 'pipe' });
      return { content: [{ type: 'text', text: `Successfully applied patch ${path.basename(patch)}` }] };
    } catch (err) {
      return { content: [{ type: 'text', text: `Failed to apply patch: ${err.message}` }] };
    }
  }

  if (name === 'init_testfly_project') {
    const dir = args.directory || path.join(root, 'testfly-suite');
    if (fs.existsSync(dir) && fs.readdirSync(dir).length > 0) {
      throw new Error(`Refusing to overwrite files in non-empty directory: ${dir}`);
    }
    fs.mkdirSync(dir, { recursive: true });
    fs.mkdirSync(path.join(dir, 'src', 'test', 'java', 'com', 'example', 'tests'), { recursive: true });

    fs.copyFileSync(path.join(__dirname, '..', 'templates', 'testfly.yml'), path.join(dir, 'testfly.yml'));

    fs.writeFileSync(path.join(dir, 'pom.xml'), `<?xml version="1.0" encoding="UTF-8"?>
<project xmlns="http://maven.apache.org/POM/4.0.0"
         xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
         xsi:schemaLocation="http://maven.apache.org/POM/4.0.0 http://maven.apache.org/xsd/maven-4.0.0.xsd">
    <modelVersion>4.0.0</modelVersion>

    <groupId>com.example</groupId>
    <artifactId>testfly-suite</artifactId>
    <version>1.0.0-SNAPSHOT</version>

    <properties>
        <maven.compiler.release>21</maven.compiler.release>
        <project.build.sourceEncoding>UTF-8</project.build.sourceEncoding>
        <testfly.version>1.0.7</testfly.version>
    </properties>

    <dependencies>
        <dependency>
            <groupId>io.github.hakanngul</groupId>
            <artifactId>testfly</artifactId>
            <version>\${testfly.version}</version>
            <scope>test</scope>
        </dependency>
    </dependencies>

    <build>
        <plugins>
            <plugin>
                <groupId>org.apache.maven.plugins</groupId>
                <artifactId>maven-compiler-plugin</artifactId>
                <version>3.13.0</version>
            </plugin>
            <plugin>
                <groupId>org.apache.maven.plugins</groupId>
                <artifactId>maven-surefire-plugin</artifactId>
                <version>3.2.5</version>
            </plugin>
        </plugins>
    </build>
</project>
`, 'utf8');

    fs.writeFileSync(path.join(dir, 'src', 'test', 'java', 'com', 'example', 'tests', 'SampleWebTest.java'), `package com.example.tests;

import io.testfly.test.BaseTest;
import org.testng.annotations.Test;

public class SampleWebTest extends BaseTest {

    @Test
    public void testExampleDotCom() {
        open("/");
        assertThatPage().hasTitle("Example Domain");
    }
}
`, 'utf8');

    return { content: [{ type: 'text', text: `Scaffolded TestFly project at ${dir}` }] };
  }

  throw new Error(`Unknown tool: ${name}`);
}

// CLI argument handling
const cliArgs = process.argv.slice(2);
if (cliArgs.length > 0) {
  const command = cliArgs[0];
  if (command === 'init') {
    const targetDir = cliArgs[1] || 'testfly-suite';
    const targetPath = path.resolve(process.cwd(), targetDir);
    const result = handleToolCall('init_testfly_project', { directory: targetPath });
    console.log(`✈️  ${result.content[0].text}`);
    console.log(`Next steps:\n  cd ${targetDir}\n  mvn test`);
    process.exit(0);
  }
  if (command === '--version' || command === '-v') {
    console.log(`${SERVER_NAME} v${SERVER_VERSION}`);
    process.exit(0);
  }
  if (command === '--help' || command === '-h') {
    console.log(`Usage:
  npx @testfly/mcp init [directory]   Scaffold a ready-to-run TestFly Java 21 test suite
  npx @testfly/mcp                    Start stdio JSON-RPC MCP server for Cursor / Claude`);
    process.exit(0);
  }
}

// JSON-RPC stdio loop
const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  terminal: false
});

rl.on('line', (line) => {
  if (!line.trim()) return;
  try {
    const msg = JSON.parse(line);
    const { id, method, params } = msg;

    if (method === 'initialize') {
      const response = {
        jsonrpc: '2.0',
        id,
        result: {
          protocolVersion: '2024-11-05',
          serverInfo: {
            name: SERVER_NAME,
            version: SERVER_VERSION
          },
          capabilities: {
            tools: {}
          }
        }
      };
      process.stdout.write(JSON.stringify(response) + '\n');
    } else if (method === 'notifications/initialized') {
      // no response required
    } else if (method === 'tools/list') {
      const response = {
        jsonrpc: '2.0',
        id,
        result: {
          tools: TOOLS
        }
      };
      process.stdout.write(JSON.stringify(response) + '\n');
    } else if (method === 'tools/call') {
      try {
        const result = handleToolCall(params.name, params.arguments || {});
        process.stdout.write(JSON.stringify({ jsonrpc: '2.0', id, result }) + '\n');
      } catch (err) {
        process.stdout.write(JSON.stringify({
          jsonrpc: '2.0',
          id,
          error: { code: -32603, message: err.message }
        }) + '\n');
      }
    } else {
      process.stdout.write(JSON.stringify({
        jsonrpc: '2.0',
        id,
        error: { code: -32601, message: 'Method not found' }
      }) + '\n');
    }
  } catch (e) {
    // Ignore invalid JSON lines
  }
});
